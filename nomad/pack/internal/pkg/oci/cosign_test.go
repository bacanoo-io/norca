package oci

import (
	"context"
	"os"
	"os/exec"
	"path/filepath"
	"testing"

	"github.com/shoenig/test/must"

	"github.com/hashicorp/nomad/pack/internal/pkg/oci/ocitest"
	"github.com/hashicorp/nomad/pack/internal/pkg/signing"
)

// TestCosignInterop checks signatures against the cosign CLI in both
// directions. It is enabled by NORCA_PACK_COSIGN=<path to cosign binary>.
func TestCosignInterop(t *testing.T) {
	cosign := os.Getenv("NORCA_PACK_COSIGN")
	if cosign == "" {
		t.Skip("set NORCA_PACK_COSIGN to the cosign binary to run the interoperability test")
	}
	ctx := context.Background()
	srv := ocitest.New().Start()
	defer srv.Close()

	a, _ := buildTestArtifact(t)
	loc := Location{Host: srv.Host(), Repository: "packs/simple_raw_exec"}
	repo, err := (&Options{PlainHTTP: true, NoDockerConfig: true}).Repository(loc)
	must.NoError(t, err)
	must.NoError(t, a.Push(ctx, repo, "0.0.1"))
	ref := loc.RepositoryName() + "@" + a.Digest()

	dir := t.TempDir()
	password := "interop"
	kp, err := signing.GenerateKeyPair([]byte(password))
	must.NoError(t, err)
	must.NoError(t, os.WriteFile(filepath.Join(dir, "norca.key"), kp.PrivateKeyPEM, 0o600))
	must.NoError(t, os.WriteFile(filepath.Join(dir, "norca.pub"), kp.PublicKeyPEM, 0o644))

	run := func(args ...string) string {
		t.Helper()
		cmd := exec.Command(cosign, args...)
		cmd.Dir = dir
		cmd.Env = append(os.Environ(), "COSIGN_PASSWORD="+password, "COSIGN_YES=true")
		out, err := cmd.CombinedOutput()
		must.NoError(t, err, must.Sprintf("cosign %v:\n%s", args, out))
		return string(out)
	}

	// Signed by Norca, verified by cosign.
	priv, err := signing.DecryptPrivateKey(kp.PrivateKeyPEM, []byte(password))
	must.NoError(t, err)
	payload, err := signing.NewPayload(loc.RepositoryName(), a.Digest())
	must.NoError(t, err)
	sig, err := signing.Sign(priv, payload)
	must.NoError(t, err)
	must.NoError(t, AttachSignature(ctx, repo, a.Digest(), signing.Signature{Payload: payload, Signature: sig}, priv.Public()))
	run("verify", "--key", "norca.pub", "--insecure-ignore-tlog=true", "--allow-http-registry=true", ref)

	// A key generated by cosign signs, Norca verifies. cosign signs with
	// its own key; the Norca signature stays.
	run("generate-key-pair", "--output-key-prefix", "cosign")
	run("sign", "--key", "cosign.key", "--tlog-upload=false", "--allow-http-registry=true", "--use-signing-config=false", "--new-bundle-format=false", ref)

	sigs, err := FetchSignatures(ctx, repo, a.Digest())
	must.NoError(t, err)
	cosignPub, err := signing.LoadPublicKey(filepath.Join(dir, "cosign.pub"))
	must.NoError(t, err)
	must.True(t, signing.Verify(a.Digest(), sigs, []*signing.PublicKey{cosignPub}).Verified)

	// Norca can sign with a key generated by cosign.
	cosignKey, err := os.ReadFile(filepath.Join(dir, "cosign.key"))
	must.NoError(t, err)
	_, err = signing.DecryptPrivateKey(cosignKey, []byte(password))
	must.NoError(t, err)
}
