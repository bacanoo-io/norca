/* eslint-env node */
'use strict';

// Generates app/utils/icons/tabler.js: the SVG nodes of the Tabler Icons
// (MIT) that the UI uses, so the bundle does not carry the full icon set.
// Add a name to ICONS and run `node scripts/generate-icons.js`.

const fs = require('fs');
const path = require('path');

const ICONS = [
  'activity',
  'alert-circle',
  'alert-triangle',
  'arrows-maximize',
  'bell',
  'book',
  'box',
  'briefcase',
  'check',
  'chevron-down',
  'chevron-right',
  'chevron-left',
  'circle-check',
  'circle-x',
  'clipboard-list',
  'cloud-upload',
  'database',
  'dots-vertical',
  'external-link',
  'git-branch',
  'hierarchy-3',
  'history',
  'info-circle',
  'key',
  'layout-dashboard',
  'layout-sidebar-left-collapse',
  'layout-sidebar-left-expand',
  'list-details',
  'lock',
  'logout',
  'menu-2',
  'moon',
  'package',
  'player-play',
  'plus',
  'refresh',
  'search',
  'server',
  'server-2',
  'settings',
  'shield-check',
  'shield-lock',
  'stack-2',
  'sun',
  'terminal-2',
  'topology-star-3',
  'user',
  'variable',
  'world',
  'x',
];

const root = path.join(__dirname, '..');
const nodes = require(path.join(
  root,
  'node_modules/@tabler/icons/tabler-nodes-outline.json'
));
const version = require(path.join(
  root,
  'node_modules/@tabler/icons/package.json'
)).version;

const out = {};
for (const name of [...ICONS].sort()) {
  if (!nodes[name]) throw new Error(`unknown Tabler icon: ${name}`);
  out[name] = nodes[name];
}

const header = `/**
 * Generated by scripts/generate-icons.js from @tabler/icons ${version}.
 * Do not edit by hand.
 *
 * SPDX-FileCopyrightText: 2020-2026 Paweł Kuna (Tabler Icons)
 * SPDX-License-Identifier: MIT
 */

`;

const body = `export default ${JSON.stringify(out, null, 2)};\n`;
const target = path.join(root, 'app/utils/icons/tabler.js');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, header + body);
console.log(`wrote ${Object.keys(out).length} icons to ${target}`);
