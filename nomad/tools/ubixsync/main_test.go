func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		p := filepath.Join(root, filepath.FromSlash(subtreeDir), filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func readTree(t *testing.T, root, rel string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(subtreeDir), filepath.FromSlash(rel)))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestRun(t *testing.T) {
	oldKeep, oldExport := keepPackages, exportPackages
	t.Cleanup(func() { keepPackages, exportPackages = oldKeep, oldExport })
	keepPackages = []string{"storage", "storage/storagetest", "kv"}
	exportPackages = []string{"storage", "kv"}

	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"LICENSE":        "BSD 3-Clause License\n",
		"README.md":      "readme\n",
		"Makefile":       "all:\n",
		"go.mod":         "module " + upstreamModule + "\n",
		"docs/DESIGN.md": "design\n",
		"cmd/x/main.go":  "package main\n\nfunc main() {}\n",
		"internal/api/api.go": `package api

import _ "` + upstreamModule + `/internal/kv"
`,
		"internal/storage/storage.go": `package storage

import "errors"

// ErrInvalidKey is an error.
var ErrInvalidKey = errors.New("invalid")

// Backend stores blobs.
type Backend interface{ Get(string) ([]byte, error) }

type hidden struct{}

const DefaultTTL = 5

func NewMemoryBackend() Backend { return nil }

func (hidden) Exported() {}
`,
		"internal/storage/mysql.go":         "package storage\n\nimport _ \"github.com/go-sql-driver/mysql\"\n",
		"internal/storage/retry.go":         "package storage\n",
		"internal/storage/storagetest/x.go": "package storagetest\n\nimport \"" + upstreamModule + "/internal/storage\"\n\nvar _ storage.Backend\n",
		"internal/kv/kv.go": `package kv

import (
	"context"

	"` + upstreamModule + `/internal/storage"
	"github.com/dzz/other"
)

type Engine struct{ s storage.Backend }

func New(s storage.Backend) *Engine { _ = context.Background; _ = other.X; return &Engine{s} }
`,
		"internal/kv/kv_test.go": "package kv\n\nimport \"" + upstreamModule + "/internal/storage\"\n\nvar _ storage.Backend\n",
	})

	problems, err := run(root, true)
	if err != nil {
		t.Fatal(err)
	}
	var removals []string
	for _, p := range problems {
		removals = append(removals, strings.TrimPrefix(p, "not used by Norca, remove: "))
	}
	want := []string{"Makefile", "cmd", "go.mod", "internal/api", "internal/storage/mysql.go", "internal/storage/retry.go"}
	if !reflect.DeepEqual(removals, want) {
		t.Fatalf("check: got %q, want %q", removals, want)
	}

	if problems, err := run(root, false); err != nil || len(problems) != 0 {
		t.Fatalf("adapt: %v %v", problems, err)
	}
	if problems, err := run(root, true); err != nil || len(problems) != 0 {
		t.Fatalf("check after adapting: %v %v", problems, err)
	}

	for _, gone := range want {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(subtreeDir), gone)); !os.IsNotExist(err) {
			t.Errorf("%s was not removed", gone)
		}
	}
	for _, kept := range []string{"LICENSE", "README.md", "docs/DESIGN.md"} {
		readTree(t, root, kept)
	}

	kv := readTree(t, root, "internal/kv/kv.go")
	if strings.Contains(kv, upstreamModule) || !strings.Contains(kv, `"`+norcaPath+`/internal/storage"`) {
		t.Errorf("kv.go imports not rewritten:\n%s", kv)
	}
	// The rewritten path sorts after the other import of the group.
	if strings.Index(kv, "github.com/dzz/other") > strings.Index(kv, norcaPath+"/internal/storage") {
		t.Errorf("kv.go imports not sorted:\n%s", kv)
	}
	if s := readTree(t, root, "internal/kv/kv_test.go"); strings.Contains(s, upstreamModule) {
		t.Errorf("kv_test.go imports not rewritten:\n%s", s)
	}

	facade := readTree(t, root, "export/storage/"+exportFile)
	for _, s := range []string{
		"// Code generated by nomad/tools/ubixsync. DO NOT EDIT.",
		"SPDX-License-Identifier: MPL-2.0",
		"package storage",
		`import ubix "` + norcaPath + `/internal/storage"`,
		"Backend = ubix.Backend",
		"DefaultTTL = ubix.DefaultTTL",
		"ErrInvalidKey = ubix.ErrInvalidKey",
		"NewMemoryBackend = ubix.NewMemoryBackend",
	} {
		if !strings.Contains(facade, s) {
			t.Errorf("storage facade lacks %q:\n%s", s, facade)
		}
	}
	if strings.Contains(facade, "hidden") || strings.Contains(facade, "Exported") {
		t.Errorf("storage facade exports unexported or method names:\n%s", facade)
	}

	// A facade that is edited by hand, or left over, is reported.
	writeTree(t, root, map[string]string{
		"export/kv/" + exportFile:    "package kv\n",
		"export/token/" + exportFile: "package token\n",
	})
	problems, err = run(root, true)
	if err != nil {
		t.Fatal(err)
	}
	want = []string{"stale facade: export/token/" + exportFile, "facade out of date: export/kv/" + exportFile}
	if !reflect.DeepEqual(problems, want) {
		t.Fatalf("check: got %q, want %q", problems, want)
	}
}

func TestExportedDeclsRejectsMutableVariables(t *testing.T) {
	dir := t.TempDir()
	src := "package p\n\nvar Timeout = 5\n"
	if err := os.WriteFile(filepath.Join(dir, "p.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, _, err := exportedDecls(dir); err == nil || !strings.Contains(err.Error(), "Timeout") {
		t.Fatalf("got %v, want an error about Timeout", err)
	}
}
